function catalogGallery(slug: string, title: string): ProductImage[] {
  return [
    {
      src: `/products/${slug}/main.webp`,
      alt: `${title} - studio catalog front view`,
      type: 'main',
      note:
        'Catalog studio image for development and staging display. Physical product photography must still be verified against supplier SKU, dimensions, finish and upholstery before production launch.',
    },
    {
      src: `/products/${slug}/front.webp`,
      alt: `${title} - alternate studio catalog view`,
      type: 'front',
      note:
        'Catalog photography pending physical product inspection and supplier media verification.',
    },
  ];
}

function pendingPackageDimensions(): Product['packageDimensions'] {
  return {
    width: null,
    height: null,
    depth: null,
    unit: 'in',
    note: VR,
  };
}

type ProductInput = Omit<
  Product,
  | 'imageGallery'
  | 'imageSourceRecord'
  | 'imageVerificationStatus'
  | 'specificationVerificationStatus'
  | 'safetyVerificationStatus'
  | 'productionReady'
  | 'currency'
> & {
  imageVerificationStatus?: Product['imageVerificationStatus'];
  imageGallery?: ProductImage[];
};

function defineProduct(input: ProductInput): Product {
  return {
    ...input,
    currency: 'USD',
    imageGallery: input.imageGallery ?? catalogGallery(input.slug, input.title),
    imageSourceRecord: PSD,
    imageVerificationStatus: input.imageVerificationStatus ?? 'pending',
    specificationVerificationStatus: 'pending',
    safetyVerificationStatus: 'pending',
    productionReady: false,
  };
}

